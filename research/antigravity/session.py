"""Local Antigravity M02 evidence kit; strictly integrity/metadata, not real-client attestation.

Operators must independently run Antigravity and retain actual client-native
records. This program NEVER connects to Antigravity, reads a private evaluator
oracle, executes received files, or approves experimental P2.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import secrets
import stat
import sys

REPO = Path(__file__).resolve().parents[2]
RELEASE = "6.9.0"
MAX_EVIDENCE_BYTES = 2 * 1024 * 1024
ARTIFACTS = {
    "tool_catalog": ("tool-catalog.txt", "tool-catalog.png"),
    "targets_call": ("targets-call.txt", "targets-call.png"),
    "inspection_call": ("inspection-call.txt", "inspection-call.png"),
    "decision_record": ("decision-record.txt", "decision-record.png"),
}
CLIENTS = ("ANTIGRAVITY_2_0", "ANTIGRAVITY_IDE", "ANTIGRAVITY_CLI")
ID = re.compile(r"^[a-f0-9]{20}$")


class EvidenceError(ValueError):
    pass


def _external(path: Path) -> Path:
    p = path.expanduser().absolute()
    if p.resolve().is_relative_to(REPO):
        raise EvidenceError("PRIVATE_EVIDENCE_MUST_BE_OUTSIDE_PUBLIC_GIT_REPO")
    if p.is_symlink():
        raise EvidenceError("SYMLINK_PRIVATE_ROOT_FORBIDDEN")
    return p


def _no_source_read(file: Path) -> tuple[int, str]:
    """Checks and hashes bytes only. Never puts content in reports or stdout."""
    try:
        info = file.lstat()
    except OSError as exc:
        raise EvidenceError("MISSING_PRIVATE_EVIDENCE_FILE") from exc
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_size > MAX_EVIDENCE_BYTES:
        raise EvidenceError("PRIVATE_EVIDENCE_MUST_BE_BOUNDED_REGULAR_FILE")
    hasher = hashlib.sha256()
    with file.open("rb") as f:
        while data := f.read(65536):
            hasher.update(data)
    return info.st_size, hasher.hexdigest()


